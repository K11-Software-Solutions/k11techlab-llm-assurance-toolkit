"""Generate the 18 study target configs: 3 models x 3 app types x 2 hardening levels.

    python study/generate_targets.py [--models study/models.yaml] [--out study/targets]

Each file is a normal target YAML (type: instrumented) usable with
`llm-assure run` and `llm-assure adaptive`.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

APPS = ("support", "rag", "hr")
HARDENING = ("baseline", "hardened")
PACK = {"support": "instrumented_support", "rag": "instrumented_rag", "hr": "instrumented_hr"}


def main() -> None:
    here = Path(__file__).parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default=str(here / "models.yaml"))
    ap.add_argument("--out", default=str(here / "targets"))
    args = ap.parse_args()

    models = yaml.safe_load(Path(args.models).read_text(encoding="utf-8"))["models"]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    count = 0
    for m in models:
        for app in APPS:
            for hardening in HARDENING:
                cfg = {
                    "name": f"Study {app} bot ({hardening}, {m['id']})",
                    "type": "instrumented",
                    "app": app,
                    "hardening": hardening,
                    "backend": m["backend"],
                    "model": m["model"],
                    "canary": "auto",
                }
                for key in ("base_url", "api_key_env", "effort"):
                    if key in m:
                        cfg[key] = m[key]
                header = (f"# Generated by study/generate_targets.py. Study pack: study/packs/{PACK[app]}.yaml\n"
                          f"#   llm-assure run -t <this file> --pack study/packs -s {PACK[app]}\n")
                path = out / f"{m['id']}__{app}__{hardening}.yaml"
                path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
                count += 1
    print(f"wrote {count} target configs to {out}")


if __name__ == "__main__":
    main()
